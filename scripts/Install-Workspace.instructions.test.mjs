withWorkspace('remove and uninstall delete unchanged generated files and keep changed generated files', (ctx) => {
  declare(ctx, names.org);
  assert.equal(install(ctx, ['-Runtimes', 'claude,opencode']).status, 0);
  const agents = join(ctx.workspace, 'AGENTS.md');
  const originalAgents = readFileSync(agents);
  writeFileSync(agents, 'edited\n');
  const remove = install(ctx, ['-Remove', '-Layers', names.org]);
  assert.equal(remove.status, 0, plainOutput(remove));
  assert.equal(readFileSync(agents, 'utf8'), 'edited\n');
  assert.ok(!existsSync(join(ctx.workspace, 'CLAUDE.md')));
  writeFileSync(agents, originalAgents);
  const restoreSelection = install(ctx, ['-Layers', names.org]);
  assert.equal(restoreSelection.status, 0, plainOutput(restoreSelection));
  const claude = join(ctx.workspace, 'CLAUDE.md');
  writeFileSync(claude, 'edited by hand\n');
  const uninstall = install(ctx, ['-Uninstall']);
  assert.equal(uninstall.status, 0, plainOutput(uninstall));
  assert.ok(!existsSync(agents), 'uninstall deletes the unchanged generated AGENTS.md');
  assert.equal(readFileSync(claude, 'utf8'), 'edited by hand\n', 'uninstall keeps the hand-edited generated CLAUDE.md');
});

// Ask the shell that runs the probe: where.exe can find a name that pwsh cannot run.
const codexPath = spawnSync('pwsh', ['-NoProfile', '-NonInteractive', '-Command', 'if (Get-Command codex -ErrorAction SilentlyContinue) { exit 0 } else { exit 1 }'], { windowsHide: true, encoding: 'utf8' });
const codexAvailable = codexPath.status === 0;
const codexProbeName = 'Codex debug prompt-input reads generated workspace instructions from a nested repository with the marker';
// withWorkspace takes workspace options, not test options, so the skip is decided here.
if (!codexAvailable) test(codexProbeName, { skip: 'codex is not available' }, () => {});
else withWorkspace(codexProbeName, (ctx) => {
  declare(ctx, names.org, 'workspace.md', 'workspace probe unique 6e14649c\n');
  assert.equal(install(ctx, ['-Runtimes', 'codex', '-Layers', names.org]).status, 0);
  const nested = join(ctx.workspace, 'projects', 'repos', 'nested');
  mkdirSync(nested, { recursive: true });
  for (const args of [['init', '-q'], ['config', 'user.name', 'test'], ['config', 'user.email', 'test@example.invalid']]) {
    const git = spawnSync('git', args, { windowsHide: true, cwd: nested, encoding: 'utf8' });
    assert.equal(git.status, 0, git.stderr);
  }
  const codeHome = join(ctx.base, 'empty-codex-home');
  mkdirSync(codeHome);
  const command = `$env:CODEX_HOME = '${codeHome.replaceAll("'", "''")}'; codex debug prompt-input -c 'project_root_markers=["stack.lock.json"]'`;
  const run = spawnSync('pwsh', ['-NoProfile', '-NonInteractive', '-Command', command], {
    windowsHide: true,
    cwd: nested,
    encoding: 'utf8',
    env: { ...process.env, CODEX_HOME: codeHome },
  });
  assert.equal(run.status, 0, `${run.stdout}\n${run.stderr}`);
  assert.match(`${run.stdout}\n${run.stderr}`, /workspace probe unique 6e14649c/);
});

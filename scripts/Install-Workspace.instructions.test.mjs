for (const [title, existing] of [['user AGENTS.md', 'AGENTS.md'], ['user CLAUDE.md', 'CLAUDE.md']]) {
  withWorkspace(`${title} collision writes only the fallback and keeps the user bytes`, (ctx) => {
    declare(ctx, names.org);
    const userBytes = Buffer.from('my instructions\r\n');
    writeFileSync(join(ctx.workspace, existing), userBytes);
    const run = install(ctx, ['-Runtimes', 'claude,opencode']);
    assert.equal(run.status, 0, plainOutput(run));
    assert.deepEqual(readFileSync(join(ctx.workspace, existing)), userBytes);
    const fallback = join(ctx.workspace, '.maxstack', 'workspace-instructions.md');
    assert.ok(existsSync(fallback));
    assert.ok(!existsSync(join(ctx.workspace, existing === 'AGENTS.md' ? 'CLAUDE.md' : 'AGENTS.md')));
    const lock = readJson(lockPath(ctx));
    assert.equal(layerRecord(lock, existing), undefined);
    assert.ok(layerRecord(lock, '.maxstack/workspace-instructions.md'));
    const config = readJson(join(ctx.workspace, 'opencode.jsonc'));
    assert.ok(config.instructions.includes('./.maxstack/workspace-instructions.md'));
    assert.match(plainOutput(run), /Kept workspace .* not written by maxstack/);
  });
}

